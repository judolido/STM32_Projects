	void calculate_pi(int precision, double *storage){
		double buff = 0;
		//main formula
		// 4/ precision*2 - 1
		while (precision >= 1){
			if (iseven(precision)){
				buff -= 4.0f / ((precision*2) - 1);

			} else {
			buff += 4.0f / ((precision*2) - 1);
			}

			precision--;
		}

		*storage = buff;
	}


